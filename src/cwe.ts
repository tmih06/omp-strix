/** Map a vulnerability class to its recommended hunter skill. */
export function classToSkill(cls: VulnClass): string {
  switch (cls) {
    case "INJECTION":
      return "vulnerabilities/sql_injection";
    case "XSS":
      return "vulnerabilities/xss";
    case "AUTH":
      return "vulnerabilities/authentication_jwt";
    case "AUTHZ":
      return "vulnerabilities/broken_function_level_authorization";
    case "SSRF":
      return "vulnerabilities/ssrf";
    case "MISC":
      return "vulnerabilities/business_logic";
  }
}
